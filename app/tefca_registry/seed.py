class _Gen:
    """Builds all rows in memory, applies the 36 defects, then exposes row lists."""

    def __init__(self):
        self.rng = random.Random(_SEED)
        self.entities: list[dict] = []
        self.identifiers: list[dict] = []
        self.relationships: list[dict] = []
        self.endpoints: list[dict] = []
        self.versions: list[dict] = []
        self.by_key: dict[str, dict] = {}
        self.children_of: dict[str, list[str]] = {}   # parent key -> child keys
        self.qhin_of: dict[str, str] = {}             # entity key -> qhin key
        self._npi_seq = 0
        self._tefca_seq = 0
        self._hcid_seq = 0
        self._ccn_seq = 0
        self._clia_seq = 0
        self._naic_seq = 0
        self.defects: list[dict] = []                 # concrete defect records for the doc

    # ---- id issuers -----------------------------------------------------------
    def next_tefcaid(self):
        self._tefca_seq += 1
        return f"TEFCA-{self._tefca_seq:06d}"

    def next_hcid(self):
        self._hcid_seq += 1
        return f"2.16.840.1.113883.3.9999.{self._hcid_seq:05d}"

    def next_npi(self, *, valid=True):
        self._npi_seq += 1
        return _npi(f"1234{self._npi_seq:05d}", valid=valid)

    def next_ccn(self):
        self._ccn_seq += 1
        return f"99{self._ccn_seq:04d}"

    def next_clia(self):
        self._clia_seq += 1
        return f"99D{self._clia_seq:07d}"

    def next_naic(self):
        self._naic_seq += 1
        return f"99{self._naic_seq:03d}"

    # ---- entity + identifier builders -----------------------------------------
    def add_entity(self, key, name, level, etype, state, *, op_status="active",
                   ver_status="verified", designation_date=None, onboarding_date=None,
                   is_active=True, purposes=None):
        city = self.rng.choice(_CITY)
        ent = dict(
            key=key,
            id=_id("entity", key),
            name=name,
            display_name=name,
            entity_level=level,
            entity_type=etype,
            operational_status=op_status,
            verification_status=ver_status,
            state=state,
            address=f"{self.rng.randint(100, 9899)} {self.rng.choice(_NOUN)} St",
            city=city,
            zip=f"{self.rng.randint(10000, 99999):05d}",
            county=f"{self.rng.choice(_COUNTY)} County",
            designation_date=designation_date,
            onboarding_date=onboarding_date,
            fhir_resource=None,           # filled after identifiers/relationships
            exchange_purposes={"purposes": purposes or ["treatment", "healthcare_operations"]},
            current_version=1,
            is_active=is_active,
        )
        self.entities.append(ent)
        self.by_key[key] = ent
        return ent

    def add_identifier(self, entity_key, itype, value, *, system_uri="_default",
                       is_primary=False, status="active", effective=None, end=None,
                       tag=None):
        uri = SYSTEM_URI.get(itype) if system_uri == "_default" else system_uri
        # unique id incorporates a tag so a defect can add a duplicate value row.
        idkey = f"{entity_key}:{itype}:{tag or value}"
        row = dict(
            id=_id("ident", idkey),
            entity_id=self.by_key[entity_key]["id"],
            identifier_type=itype,
            identifier_value=value,
            system_uri=uri,
            is_primary=is_primary,
            identifier_status=status,
            effective_date=effective,
            end_date=end,
        )
        self.identifiers.append(row)
        return row

    def add_relationship(self, parent_key, child_key, rtype, effective, *,
                         end=None, status="active", source="import", notes=None,
                         tag=""):
        relkey = f"{parent_key}->{child_key}:{rtype}:{effective.isoformat()}:{tag}"
        row = dict(
            id=_id("rel", relkey),
            parent_entity_id=self.by_key[parent_key]["id"],
            child_entity_id=self.by_key[child_key]["id"],
            relationship_type=rtype,
            effective_date=effective,
            end_date=end,
            status=status,
            source=source,
            notes=notes,
        )
        self.relationships.append(row)
        return row

    def add_endpoint(self, entity_key, etype="fhir_r4"):
        ent = self.by_key[entity_key]
        row = dict(
            id=_id("ep", f"{entity_key}:{etype}"),
            entity_id=ent["id"],
            endpoint_type=etype,
            url=f"https://fhir.{entity_key}.example.org/r4",
            connection_type="SMART on FHIR",
            name=f"{ent['name']} FHIR R4 Endpoint",
            description=f"Synthetic {etype} endpoint for {ent['name']}.",
            status="active",
            payload_type="application/fhir+json",
            environment="production",
            managing_org_id=ent["id"],
        )
        self.endpoints.append(row)
        return row

    # ---- standard identifier bundle per entity --------------------------------
    def issue_standard_identifiers(self, ent):
        key, level, etype = ent["key"], ent["entity_level"], ent["entity_type"]
        # Mandatory TEFCAID + HCID (TEFCAID primary).
        self.add_identifier(key, "tefcaid", self.next_tefcaid(), is_primary=True)
        self.add_identifier(key, "hcid", self.next_hcid())
        # NPI ~85%: skip for QHINs and vendor/clearinghouse (the IT/no-NPI ~15%).
        no_npi_type = etype in ("vendor", "clearinghouse")
        if level != "qhin" and not no_npi_type and self.rng.random() < 0.90:
            self.add_identifier(key, "npi", self.next_npi())
        # CCN ~20% (facility-ish types).
        if etype in ("hospital_system",) or self.rng.random() < 0.15:
            if level != "qhin":
                self.add_identifier(key, "ccn", self.next_ccn())
        # CLIA for laboratories (~5% overall).
        if etype == "laboratory":
            self.add_identifier(key, "clia", self.next_clia())
        # NAIC for health plans (~10% overall).
        if etype == "health_plan":
            self.add_identifier(key, "naic", self.next_naic())

