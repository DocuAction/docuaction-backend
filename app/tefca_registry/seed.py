async def run():
    gen = _Gen().generate()
    await _ensure_tables()
    async with async_session_maker() as session:
        await seed_all(session, gen)
        await session.commit()
        counts = await validate(session)
    doc_path = write_defect_doc(gen)
    return gen, counts, doc_path


def _print_report(gen, counts, doc_path):
    print("\nTEFCA registry seed — record counts")
    print("=" * 60)
    print(f"{'table':<32}{'count':>8}{'target':>10}  ok")
    print("-" * 60)
    all_ok = True
    for table, expected in EXPECTED.items():
        actual = counts.get(table, 0)
        if table in _FLOOR:
            ok = actual >= expected
            tgt = f">={expected}"
        elif table in _TOLERANCE:
            ok = abs(actual - expected) <= _TOLERANCE[table]
            tgt = f"~{expected}"
        else:
            ok = actual == expected
            tgt = str(expected)
        all_ok &= ok
        print(f"{table:<32}{actual:>8}{tgt:>10}  {'OK' if ok else 'CHECK'}")
    print("=" * 60)
    print(f"defects embedded: {len(gen.defects)} (expected 36)")
    print(f"defect doc: {doc_path}")
    print("RESULT:", "ALL COUNTS WITHIN TARGET" if all_ok and len(gen.defects) == 36
          else "REVIEW NEEDED")
    return all_ok and len(gen.defects) == 36


def main():
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")
    gen, counts, doc_path = asyncio.run(run())
    ok = _print_report(gen, counts, doc_path)
    return 0 if ok else 1


