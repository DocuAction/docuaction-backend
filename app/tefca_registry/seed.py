    lines.append("")
    by_cat = {"identity": [], "hierarchy": [], "verification": []}
    for d in gen.defects:
        by_cat[d["category"]].append(d)
    titles = {"identity": "Identity Defects (12)",
              "hierarchy": "Hierarchy Defects (12)",
              "verification": "Verification Defects (12)"}
    for cat in ("identity", "hierarchy", "verification"):
        lines.append(f"## {titles[cat]}")
        lines.append("")
        lines.append("| ID | Title | Expected detection | Affected entities |")
        lines.append("|----|-------|--------------------|-------------------|")
        for d in by_cat[cat]:
            ents = "; ".join(f"{e['name']} (`{e['id'][:8]}`)" for e in d["entities"])
            lines.append(f"| {d['id']} | {d['title']} | {d['expected_detection']} | {ents} |")
