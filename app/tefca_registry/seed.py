# NPI Luhn helpers (NPI uses the Luhn algorithm over "80840" + 9-digit base)
# ══════════════════════════════════════════════════════════════════════════════

def _npi_check_digit(nine: str) -> int:
    s = "80840" + nine
    total = 0
    for i, ch in enumerate(reversed(s)):
        d = int(ch)
        if i % 2 == 0:
            d *= 2
            if d > 9:
                d -= 9
        total += d
    return (10 - (total % 10)) % 10


def _npi(nine: str, *, valid: bool = True) -> str:
    """10-digit synthetic NPI from a 9-digit base. valid=False breaks the Luhn."""
    cd = _npi_check_digit(nine)
    if not valid:
        cd = (cd + 1) % 10
    return nine + str(cd)


