    def _child_edges(self, key):
        eid = self.by_key[key]["id"]
        return [r_ for r_ in self.relationships
                if r_["child_entity_id"] == eid
                and r_["relationship_type"] in ("belongs_to", "sub_participant_of")]

    def _parent_key(self, key):
        """Return the participant key that owns this sub (from children_of)."""
        for pkey, kids in self.children_of.items():
            if key in kids:
                return pkey
        return None

    def _deactivate_child_edge(self, key):
        for e in self._child_edges(key):
            if e["status"] == "active":
                e["status"] = "inactive"
                e["end_date"] = dt.date(2025, 6, 1)

    def _historicize_child_edge(self, key):
        for e in self._child_edges(key):
            if e["status"] == "active":
                e["status"] = "historical"
                e["end_date"] = dt.date(2024, 12, 31)

    def _strip_all_edges(self, key):
        eid = self.by_key[key]["id"]
        self.relationships = [
            r_ for r_ in self.relationships
            if r_["child_entity_id"] != eid and r_["parent_entity_id"] != eid
        ]

    # ---- orchestration --------------------------------------------------------
    def generate(self):
        self.build_base()
        self.build_special_scenarios()
        self.build_defects()
