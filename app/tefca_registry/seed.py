async def _upsert(session, model, rows):
    """Multi-row upsert on PK id (deterministic ids => idempotent)."""
    if not rows:
        return
    # strip generator-only keys
    clean = [{k: v for k, v in row.items() if k != "key"} for row in rows]
    table = model.__table__
    # chunk to keep parameter counts reasonable
    CH = 200
    for i in range(0, len(clean), CH):
        batch = clean[i:i + CH]
        stmt = pg_insert(table).values(batch)
        update = {c.name: getattr(stmt.excluded, c.name)
                  for c in table.columns if c.name not in ("id", "created_at")}
        stmt = stmt.on_conflict_do_update(index_elements=["id"], set_=update)
        await session.execute(stmt)


async def _ensure_tables():
    tables = [Base.metadata.tables[t] for t in r.TEFCA_REG_TABLE_ORDER]
    async with engine.begin() as conn:
        await conn.run_sync(lambda c: Base.metadata.create_all(c, tables=tables, checkfirst=True))


async def seed_all(session, gen: _Gen):
    # entities first (FK parent), then dependents.
    await _upsert(session, r.TefcaRegEntity, gen.entities)
    await _upsert(session, r.TefcaEntityIdentifier, gen.identifiers)
    await _upsert(session, r.TefcaEntityRelationship, gen.relationships)
    await _upsert(session, r.TefcaEntityVersion, gen.versions)
    await _upsert(session, r.TefcaEntityEndpoint, gen.endpoints)
    logger.info("seeded entities=%d identifiers=%d relationships=%d versions=%d endpoints=%d",
                len(gen.entities), len(gen.identifiers), len(gen.relationships),
                len(gen.versions), len(gen.endpoints))


async def validate(session):
    counts = {}
    for table in EXPECTED:
        counts[table] = int(await session.scalar(
            select(func.count()).select_from(Base.metadata.tables[table])) or 0)
    return counts


